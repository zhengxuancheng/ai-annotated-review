import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadWidgetHtml } from "../apps/chatgpt-app/server/dist/widgetHtml.js";

process.on("uncaughtException", failAndExit);
process.on("unhandledRejection", failAndExit);

const outputPath = path.join(
  "apps",
  "chatgpt-app",
  "cloudflare-worker",
  "src",
  "generated",
  "widgetHtml.ts"
);
const widgetHtml = loadWidgetHtml();

if (!widgetHtml.includes('<div id="root">')) {
  throw new Error("Generated widget HTML is missing the React root.");
}

const source = `// Generated by scripts/generate-worker-widget.mjs. Do not edit by hand.
export const WIDGET_HTML = ${JSON.stringify(widgetHtml)} as const;
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");

console.log(
  JSON.stringify(
    {
      ok: true,
      outputPath,
      widgetHtmlChars: widgetHtml.length
    },
    null,
    2
  )
);

function failAndExit(error) {
  const reason = error instanceof Error ? error.message : String(error);
  console.error(JSON.stringify({ ok: false, reason }, null, 2));
  process.exit(1);
}
